"""Demo chart to verify matplotlib is working in this environment."""
import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np

x = np.linspace(0, 10, 200)

fig, ax = plt.subplots(figsize=(8, 4.5))
ax.plot(x, np.sin(x), linewidth=2, label="sin(x)")
ax.plot(x, np.cos(x), linewidth=2, linestyle="--", label="cos(x)")

ax.set_title("Demo Chart - Generated by Cline")
ax.set_xlabel("x")
ax.set_ylabel("y")
ax.legend()
ax.grid(alpha=0.3)

fig.tight_layout()
out = r"C:\Users\SHADHUNTER\charts\demo.png"
fig.savefig(out, dpi=150)
print(f"saved -> {out}")
